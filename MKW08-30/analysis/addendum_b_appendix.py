"""Appendix B1 of Addendum B: rows, criteria and attribute lists for the TabArena binary tasks (2026-09-24).
Reads ONLY the package's metadata files (measured-counts.csv, measured-column-counts.csv), which hold counts made at
acquisition; opens no data file, fits nothing, relates no attribute to a target.
    python addendum_b_appendix.py  ->  ADDENDUM_B_APPENDIX_B1.md, ADDENDUM_B_attribute_lists.csv
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..", "..", "TabArena-Binary")
counts = list(csv.DictReader(open(os.path.join(PKG, "measured-counts.csv"), encoding="utf-8")))
cols = list(csv.DictReader(open(os.path.join(PKG, "measured-column-counts.csv"), encoding="utf-8")))
assert len(counts) == 30

EXCLUDED_DATASETS = {"diabetes": "the Pima data, already analyzed as PIMA in the thirty (identical rows; package finding 4)"}
LIST_ALL_UP_TO = 40

out, rows_csv, k = [], [], 0
for d in sorted(counts, key=lambda r: int(r["n_rows"])):
    name = d["dataset"]
    if name in EXCLUDED_DATASETS:
        continue
    k += 1
    n = int(d["n_rows"])
    classes = dict(kv.split("=") for kv in d["class_counts"].split(";"))
    (c1, n1), (c0, n0) = sorted(classes.items(), key=lambda t: -int(t[1]))
    if n1 == n0 and "1" in classes:  # the one tie (hazelnut, 1,200 / 1,200): C1 is the value 1, as in the thirty
        (c1, n1), (c0, n0) = ("1", classes["1"]), ("0", classes["0"])
    feats = [c for c in cols if c["dataset"] == name and c["is_target"] == "no"]
    assert len(feats) == int(d["n_features"]), name
    for c in feats:
        rows_csv.append({"dataset": name, "column_index": c["column_index"], "attribute": c["column"],
                         "declared_type": c["declared_type"], "n_distinct_observed": c["n_distinct_observed"],
                         "n_missing": c["n_missing"]})
    names = [c["column"] for c in feats]
    shown = ", ".join(names) if len(names) <= LIST_ALL_UP_TO else \
        ", ".join(names[:12]) + f", and {len(names) - 12} more (full list in ADDENDUM_B_attribute_lists.csv)"
    cv = "10 x stratified 10-fold" if n <= 10000 else "1 x stratified 10-fold (n > 10,000)"
    notes = []
    if d["flag_leakage_candidates_by_name_NOT_MEASURED"]:
        notes.append("Leakage candidate named at acquisition, kept as curated: " + d["flag_leakage_candidates_by_name_NOT_MEASURED"])
    if d["flag_constant_columns"]:
        notes.append("Constant column(s), dropped by the harness itself: " + d["flag_constant_columns"])
    if d["flag_high_cardinality_gt50"]:
        notes.append("More than 50 observed values: " + d["flag_high_cardinality_gt50"])
    if d["n_columns_with_pseudo_missing_literals"] not in ("", "0"):
        notes.append(f"{d['n_columns_with_pseudo_missing_literals']} column(s) carry literal strings such as 'nan' or "
                     "'unknown', read as ordinary values")
    if d["flag_differs_from_original"]:
        notes.append("Curation: " + d["flag_differs_from_original"])
    out.append(f"**B1.{k}. {name}** (OpenML {d['openml_data_id']}, task {d['openml_task_id']}). n = {n:,}; criterion: "
               f"{d['target']}; C1 = {c1} ({int(n1):,}), C0 = {c0} ({int(n0):,}). Rows: all. Cross-validation: {cv}. "
               f"Attributes ({len(names)}): {shown}. Excluded: none beyond the target. " + " ".join(n.rstrip(".") + "." for n in notes))

with open(os.path.join(HERE, "ADDENDUM_B_APPENDIX_B1.md"), "w", encoding="utf-8") as f:
    f.write(f"## Appendix B1. The {k} TabArena binary tasks: rows, criteria and attribute lists "
            "(generated by `analysis/addendum_b_appendix.py` from the package's metadata)\n\n")
    f.write("Excluded dataset: " + "; ".join(f"{a}, {b}" for a, b in EXCLUDED_DATASETS.items()) + ".\n\n")
    f.write("\n\n".join(out) + "\n")
with open(os.path.join(HERE, "ADDENDUM_B_attribute_lists.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows_csv[0].keys()))
    w.writeheader()
    w.writerows(rows_csv)
print(k, "datasets;", len(rows_csv), "attributes; n from", min(int(d["n_rows"]) for d in counts if d["dataset"] not in EXCLUDED_DATASETS),
      "to", max(int(d["n_rows"]) for d in counts))
